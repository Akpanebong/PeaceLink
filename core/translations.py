for code, label in SUPPORTED_LANGUAGES:
    UI_TRANSLATIONS.setdefault(code, {**BASE_UI_TEXT, "language": label})
    PHRASE_TRANSLATIONS.setdefault(code, {})


def language_choices():
    return SUPPORTED_LANGUAGES


def language_label(language):
    return dict(SUPPORTED_LANGUAGES).get(language, language)


def ui_for(language):
    return UI_TRANSLATIONS.get(language, UI_TRANSLATIONS["en"])


def phrase_replacements_for(language):
    replacements = PHRASE_TRANSLATIONS.get(language, {})
    return dict(sorted(replacements.items(), key=lambda item: len(item[0]), reverse=True))
